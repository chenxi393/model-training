# -*- coding: utf-8 -*-
"""
线性回归 · 最小版

配套讲义：README.md 第 1 ~ 7 章

一个点，一个参数，不用任何库。
核心算法只有最后那 4 行，上面全是脚手架。

跑：python3 linear_regression.py
"""

# ---- 数据：一个点。真相是 y = 3x，但我们假装不知道 -----------------
x = 2.0
y = 6.0

# ---- 参数：我们猜的数，一无所知，先猜 0 ----------------------------
w = 0.0

# ---- 你自己定的两个数 --------------------------------------------
LR = 0.05      # 学习率：每次挪多远（讲义第 7 章）
STEPS = 12     # 挪多少次


# ---- 脚手架：三个小函数 ------------------------------------------

def predict(w, x):
    """用参数算预测值。讲义第 1 章：y = w·x"""
    return w * x


def loss(w, x, y):
    """算错了多少。讲义第 2 章：误差的平方"""
    return (predict(w, x) - y) ** 2


def slope(w, x, y):
    """
    loss 对 w 的斜率。讲义第 6 章的结论：

        斜率 = 2 × (预测 − 真实) × x

    怎么推出来的？README 第 5 章用初中代数展开过，只用到一个 (a+b)² = a²+2ab+b²
    """
    return 2 * (predict(w, x) - y) * x


# ==================================================================
#                        核心流程
# ==================================================================
for step in range(STEPS):
    error = predict(w, x) - y      # 1. 错在哪、错多少
    L = error ** 2                 # 2. 这次错了多重
    g = 2 * error * x              # 3. 斜率：往哪挪、挪的力度
    w = w - LR * g                 # 4. 往反方向挪一小步
    # 为什么要循环？因为 w 一变，e 就变，斜率 2·e·x 跟着变（讲义第 6 章）
# ==================================================================


print(f"学到的 w = {w:.4f}")
print(f"真实是 w = 3")
print(f"最终 loss = {loss(w, x, y):.6f}")
