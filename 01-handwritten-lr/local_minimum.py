# -*- coding: utf-8 -*-
"""
走错谷

配套问答：问答录.md · 问题 3「会不会走错谷？」

同一个函数，同一个梯度下降，同一个学习率 —— 只有起点不同，
结果差了将近一倍。而且它不知道自己错过了什么。

跑：python3 local_minimum.py
"""


def f(x):
    """这个函数的地形：两个谷底，中间隔一个小山包"""
    return x ** 4 - 2 * x ** 2 + 0.3 * x


def df(x):
    """f 对 x 的斜率。就是讲义第 6 章那套，只是换了个函数"""
    return 4 * x ** 3 - 4 * x + 0.3


# ---- 和 linear_regression.py 一模一样的循环 ----------------------
def descend(x, lr=0.02, steps=300):
    for _ in range(steps):
        g = df(x)               # 算斜率
        x = x - lr * g          # 往反方向挪一小步
    return x
# ----------------------------------------------------------------


print("同一个函数   f(x) = x⁴ − 2x² + 0.3x")
print("同一个算法，只有起点不同：\n")

for start in (-2.0, 2.0):
    end = descend(start)
    print(f"  从 x = {start:+.1f} 出发  ->  停在 x = {end:+.4f}    f = {f(end):+.4f}")

print("\n这个函数真正的三个特殊点：")
for x, kind in ((-1.0360, "谷底（全局最低）"),
                (0.0754, "山顶"),
                (0.9603, "谷底（只是局部的）")):
    print(f"  x = {x:+.4f}    f = {f(x):+.4f}    {kind}")

print("""
看出来了吗：

  从左边出发的那次，找到了全局最低（f = −1.31）。
  从右边出发的那次，卡在另一个谷底（f = −0.71），差了将近一倍。

  而且它【不知道自己错过了什么】—— 那个谷底的斜率是 0。
  算法问"该往哪挪"，得到的回答是"哪都不用挪"。

  要从这个谷底出去，只能先往左走，翻过中间那个小山包 ——
  也就是说，loss 必须先【上升】一段。
  而梯度下降永远不会主动往 loss 上升的方向走。这就是它出不来的原因。

  你现在学的线性回归不会遇到这种事，因为它的 loss 只有一个谷底。
  但神经网络会。这就是深度学习难的地方。
""")
